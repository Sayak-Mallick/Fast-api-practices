# While Loop

i = 1
while i <= 5:
    print("Hello World")
    i += 1

data = [2, 'Sayak', 4.6, 7, "Mallick", "FastApi"]

pointer = 0
while pointer < len(data):
    print(data[pointer])
    pointer += 1

# for loop
for i in range(5):
    print(f"Hello World: {i}")

for value in data:
    print(value)